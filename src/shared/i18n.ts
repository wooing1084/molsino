export type I18nKey = keyof typeof ko;
type Interpolation = Record<string, string | number>;

export function translate(locale: AppLocale, key: I18nKey, values: Interpolation = {}): string {
  return ({ ko, en }[locale][key] as string).replace(/\{(\w+)\}/g, (_match, name: string) => String(values[name] ?? `{${name}}`));
}

const commandErrorKeys: Record<CommandError, I18nKey> = {
  BUSY: 'error.BUSY', STALE_STATE: 'error.STALE_STATE', INVALID_ACTION: 'error.INVALID_ACTION',
  VALIDATION_ERROR: 'error.VALIDATION_ERROR', SAVE_FAILED: 'error.SAVE_FAILED', RECOVERY_REQUIRED: 'error.RECOVERY_REQUIRED',
};

export function commandErrorMessage(locale: AppLocale, error: CommandError): string {
  return translate(locale, commandErrorKeys[error]);
}

